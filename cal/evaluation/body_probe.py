def _replay_body_labels(
    trajectory: Trajectory,
    *,
    target_offset: str,
) -> tuple[list[list[list[bool]]], list[tuple[float, float]]]:
    world = BodyDiscoveryWorld(
        trajectory.world_config,
        trajectory.body_config,
    )
    current = world.reset(trajectory.seed)
    masks: list[list[list[bool]]] = []
    poses: list[tuple[float, float]] = []
    for experience in trajectory.experiences:
        if current != experience.observation:
            raise RuntimeError("probe replay diverged before collecting label")
        if target_offset == "current":
            masks.append(
                [list(row) for row in world.evaluation_snapshot().masks.body]
            )
            poses.append(
                (
                    world.body.state.shoulder_angle,
                    world.body.state.elbow_angle,
                )
            )
        current = world.step(experience.action).observation
        if current != experience.next_observation:
            raise RuntimeError("probe replay diverged after action")
        if target_offset == "next":
            masks.append(
                [list(row) for row in world.evaluation_snapshot().masks.body]
            )
            poses.append(
                (
                    world.body.state.shoulder_angle,
                    world.body.state.elbow_angle,
                )
            )
    return masks, poses


def _probe_loader(
    data: ProbeData,
    *,
    batch_size: int,
    shuffle: bool,
    seed: int,
) -> DataLoader[tuple[Tensor, Tensor]]:
    generator = torch.Generator()
    generator.manual_seed(seed)
    return DataLoader(
        TensorDataset(data.representations, data.body_masks),
        batch_size=batch_size,
        shuffle=shuffle,
        generator=generator,
        num_workers=0,
    )


@torch.no_grad()
def _probe_logits(
    probe: LinearBodyProbe,
    data: ProbeData,
    *,
    batch_size: int,
    device: torch.device,
) -> Tensor:
    probe.to(device)
    probe.eval()
    chunks = []
    for start in range(0, len(data), batch_size):
        features = data.representations[start : start + batch_size].to(device)
        chunks.append(probe(features).cpu())
    return torch.cat(chunks, dim=0)


def _mapping(payload: Mapping[str, Any], key: str) -> Mapping[str, Any]:
    value = payload.get(key)
    if not isinstance(value, dict):
        raise ValueError(f"{key} must be a mapping")
    return value


